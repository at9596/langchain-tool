import os
from dotenv import load_dotenv
from langchain_google_genai import ChatGoogleGenerativeAI
from langchain_core.tools import tool
from langchain_core.messages import HumanMessage, ToolMessage

# Load env variables from .env file
load_dotenv()

# 1.Define a tool using @tool decorater
@tool
def multiply(a: int, b: int) -> int:
    """Multiplies two integers together and returns the result."""
    return a*b

# 2. Initialise the Gemini chat model
llm = ChatGoogleGenerativeAI(model="gemini-3.8-flash", temperature=0)

# 3, Bind tool to Chat model
llm_with_tools = llm.bind_tools([multiply])

# 4. Invoke the model with a prompt that triggers the tool
query = "What is 45 multiplied by 12?"
response = llm_with_tools.invoke(query)

# # 5. Inspect the tool call generated by Gemini
# print("AI Response Tool Calls:")
# print(response.tool_calls)

# Execute the tool using the arguments returned by the model
tool_call = response.tool_calls[0]
tool_output = multiply.invoke(tool_call["args"])
# Pass the conversation history + tool output back to the model
messages = [
    HumanMessage(content=query),
    response,
    ToolMessage(content=str(tool_output), tool_call_id=tool_call["id"])
]

final_response = llm_with_tools.invoke(messages)
print("Final Answer:", final_response.content)